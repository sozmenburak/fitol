export function getTodayExercises() {
  const day = new Date().getDay();
  const plan = weeklyPlan[day];
  const todayExercises = [];

  plan.groups.forEach(group => {
    const groupExercises = exercises[group] || [];
    const picks = plan.pick?.[group];
    if (picks) {
      picks.forEach(idx => {
        if (groupExercises[idx]) todayExercises.push(groupExercises[idx]);
      });
    } else {
      todayExercises.push(...groupExercises.slice(0, 3));
    }
  });

  return { plan, exercises: todayExercises };
}
